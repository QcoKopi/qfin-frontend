let assemblyDetails = [];
let assemblyRecipeMap = {};
let gbDetailIds = [];

function addAssemblyDetail(mode = 'manual') {
    const id = assemblyDetails.length;
    const div = document.createElement('div'); 
    div.className = 'detail-row'; 
    div.id = `asm-detail-${id}`;
    let tag = '';
    let qtyReadonly = '';
    if (mode === 'auto') {
        tag = ' <span style="font-weight:400;color:var(--gray);font-size:11px;">(otomatis dari Master_Resep)</span>';
        qtyReadonly = 'readonly style="background:#f4f4f4;"';
    } else if (mode === 'gb') {
        tag = ' <span style="font-weight:400;color:var(--accent);font-size:11px;">(Green Bean — isi jumlah aktual)</span>';
    }
    div.innerHTML = `
        <div class="detail-row-header"><span><strong>Bahan #${id + 1}</strong>${tag}</span><button class="btn-remove" onclick="removeAssemblyDetail(${id})">Hapus</button></div>
        <div class="form-grid">
            <div class="form-group"><label class="mandatory-label">Raw Material</label><div class="searchable-dropdown"><input type="text" id="asm-raw-${id}" placeholder="Cari raw material..." oninput="searchDropdown('asm-raw-${id}', 'products')" onfocus="showDropdown('asm-raw-${id}')"><div class="dropdown-list" id="asm-raw-${id}-list"></div></div></div>
            <div class="form-group"><label class="mandatory-label">Jumlah (kg)</label><input type="number" id="asm-raw-qty-${id}" step="0.01" placeholder="0.00" onchange="onAssemblyDetailQtyChange()" ${qtyReadonly}></div>
            <div class="form-group"><label class="mandatory-label">Harga per kg</label><input type="number" id="asm-raw-price-${id}" step="1000" placeholder="0" onchange="calculateAssemblyHPP()"></div>
        </div>`;
    document.getElementById('assemblyDetails').appendChild(div);
    assemblyDetails.push(id);
    return id;
}

function removeAssemblyDetail(id) {
    const el = document.getElementById(`asm-detail-${id}`); 
    if (el) el.remove();
    assemblyDetails = assemblyDetails.filter(i => i !== id);
    delete assemblyRecipeMap[id];
    gbDetailIds = gbDetailIds.filter(i => i !== id);
    calculateAssemblyHPP();
    calculatePenyusutan();
}

function autoFillBatchNo() {
    const batchInput = document.getElementById('asmBatch');
    if (!batchInput) return;
    if (batchInput.value && batchInput.dataset.autoGenerated !== 'true') return;
    const dateVal = document.getElementById('asmDate').value;
    const sku = document.getElementById('asmSku')?.dataset.value || '';
    if (!dateVal || !sku) return;
    const [, m, d] = dateVal.split('-');
    batchInput.value = `${d}${m}-${sku}`;
    batchInput.dataset.autoGenerated = 'true';
}

async function loadRecipeForProduct(sku) {
    const result = await callGAS('getResep', { id_produk: sku });
    document.getElementById('assemblyDetails').innerHTML = ''; 
    assemblyDetails = []; 
    assemblyRecipeMap = {}; 
    gbDetailIds = [];
    if (result.success && result.data && result.data.length > 0) {
        let gbCount = 0;
        result.data.forEach((r) => {
            const isGB = !!r.is_gb;
            const id = addAssemblyDetail(isGB ? 'gb' : 'auto');
            const rawInput = document.getElementById(`asm-raw-${id}`);
            if (rawInput) { rawInput.value = r.bahan; rawInput.dataset.value = r.bahan_id || r.bahan; }
            const priceInput = document.getElementById(`asm-raw-price-${id}`);
            if (priceInput && r.harga_bahan) { priceInput.value = r.harga_bahan; }
            if (isGB) { gbDetailIds.push(id); gbCount++; }
            else { assemblyRecipeMap[id] = parseFloat(r.komposisi) || 0; }
        });
        applyRecipeQuantities();
        const gbNote = gbCount > 0 ? ` ${gbCount} di antaranya Green Bean — isi jumlah aktual secara manual.` : '';
        showAlert('info', `${result.data.length} bahan baku dimuat dari Master_Resep.${gbNote}`, 'assemblyAlert');
    } else {
        showAlert('warning', 'Tidak ada resep di Master_Resep untuk produk ini. Tambahkan bahan secara manual.', 'assemblyAlert');
    }
    calculateAssemblyHPP();
    calculatePenyusutan();
}

function applyRecipeQuantities() {
    const qtyProduksi = parseFloat(document.getElementById('asmQty').value) || 0;
    Object.keys(assemblyRecipeMap).forEach(id => {
        const komposisi = assemblyRecipeMap[id];
        const qtyInput = document.getElementById(`asm-raw-qty-${id}`);
        if (qtyInput) qtyInput.value = (komposisi * qtyProduksi).toFixed(2);
    });
}

function onAssemblyQtyChange() {
    applyRecipeQuantities();
    calculateAssemblyHPP();
    calculatePenyusutan();
}

function onAssemblyDetailQtyChange() {
    calculateAssemblyHPP();
    calculatePenyusutan();
}

function calculatePenyusutan() {
    const wasteInput = document.getElementById('asmWaste');
    if (!wasteInput) return;
    if (gbDetailIds.length === 0) {
        wasteInput.value = '0';
        return;
    }
    const jumlahProduksi = parseFloat(document.getElementById('asmQty').value) || 0;
    const basisQty = gbDetailIds.reduce((sum, id) => sum + (parseFloat(document.getElementById(`asm-raw-qty-${id}`)?.value) || 0), 0);
    if (basisQty > 0 && jumlahProduksi > 0) {
        const penyusutan = ((basisQty - jumlahProduksi) / basisQty) * 100;
        wasteInput.value = penyusutan.toFixed(2);
    } else {
        wasteInput.value = '0';
    }
}

function calculateAssemblyHPP() {
    let totalMaterial = 0;
    const qtyProduksi = parseFloat(document.getElementById('asmQty').value) || 0;
    assemblyDetails.forEach(id => {
        const qty = parseFloat(document.getElementById(`asm-raw-qty-${id}`)?.value) || 0;
        const price = parseFloat(document.getElementById(`asm-raw-price-${id}`)?.value) || 0;
        totalMaterial += qty * price;
    });
    const hpp = qtyProduksi > 0 ? totalMaterial / qtyProduksi : 0;
    document.getElementById('assemblyHPP').style.display = 'block';
    const bahanEl = document.getElementById('hppTotalBahan');
    if (bahanEl) bahanEl.textContent = 'Rp ' + formatNumber(totalMaterial.toFixed(0));
    document.getElementById('hppValue').textContent = 'Rp ' + formatNumber(hpp.toFixed(0));
}

async function submitAssembly() {
    clearMandatoryErrors('tab-assembly');
    if (!validateMandatory('tab-assembly', 'assemblyAlert')) return;
    if (assemblyDetails.length === 0) {
        showAlert('danger', 'Tambahkan minimal 1 bahan baku', 'assemblyAlert'); 
        return;
    }
    const details = assemblyDetails.map(id => ({
        raw_material: document.getElementById(`asm-raw-${id}`)?.value || '',
        raw_material_id: document.getElementById(`asm-raw-${id}`)?.dataset.value || '',
        jumlah_raw_material: parseFloat(document.getElementById(`asm-raw-qty-${id}`)?.value) || 0,
        harga_raw_material: parseFloat(document.getElementById(`asm-raw-price-${id}`)?.value) || 0
    })).filter(d => d.raw_material);
    const qtyProduksi = parseFloat(document.getElementById('asmQty').value) || 0;
    const totalMaterial = details.reduce((sum, d) => sum + (d.jumlah_raw_material * d.harga_raw_material), 0);
    const hpp = qtyProduksi > 0 ? totalMaterial / qtyProduksi : 0;
    const data = {
        tanggal: document.getElementById('asmDate').value, 
        batch_no: document.getElementById('asmBatch').value,
        sku: document.getElementById('asmSku').dataset.value || document.getElementById('asmSku').value,
        nama_barang: document.getElementById('asmNamaBarang').value, 
        jumlah_produksi: qtyProduksi,
        penyusutan: parseFloat(document.getElementById('asmWaste').value) || 0,
        total_harga_material: totalMaterial, 
        hpp: hpp, 
        details: details
    };
    const result = await callGAS('submitAssembly', data);
    if (result.success) { 
        showAlert('success', 'Assembly berhasil! ID: ' + result.id_assembly, 'assemblyAlert'); 
        clearAssemblyForm(); 
    }
    else showAlert('danger', 'Gagal: ' + result.message, 'assemblyAlert');
}

function clearAssemblyForm() {
    const asmBatch = document.getElementById('asmBatch');
    const asmSku = document.getElementById('asmSku');
    const asmNamaBarang = document.getElementById('asmNamaBarang');
    const asmQty = document.getElementById('asmQty');
    const asmWaste = document.getElementById('asmWaste');
    const assemblyDetailsEl = document.getElementById('assemblyDetails');
    const assemblyHPP = document.getElementById('assemblyHPP');

    if (asmBatch) { asmBatch.value = ''; asmBatch.dataset.autoGenerated = ''; }
    if (asmSku) { asmSku.value = ''; asmSku.dataset.value = ''; }
    if (asmNamaBarang) asmNamaBarang.value = '';
    if (asmQty) asmQty.value = ''; 
    if (asmWaste) asmWaste.value = '0';
    if (assemblyDetailsEl) assemblyDetailsEl.innerHTML = ''; 

    assemblyDetails = []; 
    assemblyRecipeMap = {}; 
    gbDetailIds = [];
    if (assemblyHPP) assemblyHPP.style.display = 'none';
}
