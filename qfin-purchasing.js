let pembelianDetails = [];

function addPembelianDetail() {
    const id = pembelianDetails.length;
    const div = document.createElement('div'); 
    div.className = 'detail-row'; 
    div.id = `pem-detail-${id}`;
    div.innerHTML = `
        <div class="detail-row-header"><span><strong>Barang #${id + 1}</strong></span><button class="btn-remove" onclick="removePembelianDetail(${id})">Hapus</button></div>
        <div class="form-grid">
            <div class="form-group"><label class="mandatory-label">Nama Barang</label><div class="searchable-dropdown"><input type="text" id="pem-barang-${id}" placeholder="Cari barang..." oninput="searchDropdown('pem-barang-${id}', 'products')" onfocus="showDropdown('pem-barang-${id}')"><div class="dropdown-list" id="pem-barang-${id}-list"></div></div></div>
            <div class="form-group"><label class="mandatory-label">Jumlah</label><input type="number" id="pem-qty-${id}" step="0.01" placeholder="0"></div>
            <div class="form-group"><label class="mandatory-label">Harga Satuan</label><input type="number" id="pem-price-${id}" step="1000" placeholder="0"></div>
            <div class="form-group"><label>Kode LOT</label><input type="text" id="pem-lot-${id}" placeholder="Otomatis setelah pilih supplier+barang" oninput="this.dataset.autoGenerated='false'"></div>
        </div>`;
    document.getElementById('pembelianDetails').appendChild(div);
    pembelianDetails.push(id);
}

function removePembelianDetail(id) { 
    const el = document.getElementById(`pem-detail-${id}`); 
    if (el) el.remove(); 
    pembelianDetails = pembelianDetails.filter(i => i !== id); 
}

function generateKodeLotJS(tanggal, namaSupplier, idBarang) {
    const d = tanggal ? new Date(tanggal) : new Date();
    const dd = d.getDate().toString().padStart(2, '0');
    const mm = (d.getMonth() + 1).toString().padStart(2, '0');
    const supplierInitials = (namaSupplier || '').toString().trim().split(/\s+/)
        .map(w => w.charAt(0).toUpperCase()).join('').slice(0, 4) || 'XX';
    const itemCode = (idBarang || '').toString().trim() || 'XX';
    return `${dd}${mm}-${supplierInitials}-${itemCode}`;
}

function updateKodeLotForRow(id) {
    const lotInput = document.getElementById(`pem-lot-${id}`);
    if (!lotInput) return;
    if (lotInput.value && lotInput.dataset.autoGenerated !== 'true') return;
    const idBarang = document.getElementById(`pem-barang-${id}`)?.dataset.value;
    const namaSupplier = document.getElementById('pemSupplier')?.value;
    if (!idBarang || !namaSupplier) return;
    lotInput.value = generateKodeLotJS(document.getElementById('pemDate')?.value, namaSupplier, idBarang);
    lotInput.dataset.autoGenerated = 'true';
}

function updateAllKodeLot() { 
    pembelianDetails.forEach(id => updateKodeLotForRow(id)); 
}

async function submitPembelian() {
    clearMandatoryErrors('tab-pembelian');
    if (!validateMandatory('tab-pembelian', 'pembelianAlert')) return;
    if (pembelianDetails.length === 0) {
        showAlert('danger', 'Tambahkan minimal 1 barang', 'pembelianAlert'); 
        return;
    }

    const pemSalesman = document.getElementById('pemSalesman');
    const pemNoDokumen = document.getElementById('pemNoDokumen');
    const pemKodeTransaksi = document.getElementById('pemKodeTransaksi');
    const pemCOA = document.getElementById('pemCOA');
    const pemSupplier = document.getElementById('pemSupplier');
    const pemStatusBayar = document.getElementById('pemStatusBayar');
    const pemDate = document.getElementById('pemDate');
    const pemCostCenter = document.getElementById('pemCostCenter');

    const details = pembelianDetails.map(id => ({
        nama_barang: document.getElementById(`pem-barang-${id}`)?.value || '',
        id_produk: document.getElementById(`pem-barang-${id}`)?.dataset.value || '',
        jumlah: parseFloat(document.getElementById(`pem-qty-${id}`)?.value) || 0,
        harga_satuan: parseFloat(document.getElementById(`pem-price-${id}`)?.value) || 0,
        total: (parseFloat(document.getElementById(`pem-qty-${id}`)?.value) || 0) * (parseFloat(document.getElementById(`pem-price-${id}`)?.value) || 0),
        kode_lot: document.getElementById(`pem-lot-${id}`)?.value || ''
    })).filter(d => d.nama_barang);

    const total = details.reduce((sum, d) => sum + d.total, 0);
    const data = {
        tanggal: pemDate?.value || '', 
        cost_center: pemCostCenter?.value || 'Q.Co',
        salesman: pemSalesman?.value || '', 
        no_dokumen: pemNoDokumen?.value || '',
        kode_transaksi: pemKodeTransaksi?.value || '', 
        coa: pemCOA?.value || '',
        nama_supplier: pemSupplier?.value || '', 
        notes: '', 
        total: total,
        status_bayar: pemStatusBayar?.value || '', 
        details: details
    };
    const result = await callGAS('submitPembelian', data);
    if (result.success) { 
        showAlert('success', 'Pembelian berhasil! ID: ' + result.id_pembelian, 'pembelianAlert'); 
        clearPembelianForm(); 
    }
    else showAlert('danger', 'Gagal: ' + result.message, 'pembelianAlert');
}

function clearPembelianForm() {
    const pemNoDokumen = document.getElementById('pemNoDokumen');
    const pemSupplier = document.getElementById('pemSupplier');
    const pemCOA = document.getElementById('pemCOA');
    const pembelianDetailsEl = document.getElementById('pembelianDetails');

    if (pemNoDokumen) pemNoDokumen.value = ''; 
    if (pemSupplier) pemSupplier.value = '';
    if (pemCOA) pemCOA.value = ''; 
    if (pembelianDetailsEl) pembelianDetailsEl.innerHTML = '';

    pembelianDetails = [];
    autoFillNextDoc('pemNoDokumen', 'Pembelian_App', 'no_dokumen', 'NOT_SAMPLE', 'FP');
}
